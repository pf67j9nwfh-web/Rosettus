/* OAH_GLITRACE=name,name,... (or "all"): log guest GL calls by name (debug, 40000 lines; OAH_GLITRACE_DELAY=s waits s seconds, -1 traces while /tmp/oah_glitrace.on exists) */
static void oah_gli_trace(const char *nm, unsigned int *R) {
    static const char *tl; static int tinit, nl;
    size_t ln; const char *p;
    static time_t t0; static int delay;
    if (!tinit) { tinit = 1; tl = getenv("OAH_GLITRACE"); delay = getenv("OAH_GLITRACE_DELAY") ? atoi(getenv("OAH_GLITRACE_DELAY")) : 0; }
    if (!tl || nl >= 40000 || !((nm[0] == 'g' && nm[1] == 'l') || nm[0] == 'a' || nm[0] == 'C')) return;
    if (delay < 0) {   /* -1: only while /tmp/oah_glitrace.on exists (checked once a second) */
        static time_t last; static int on;
        if (time(0) != last) { last = time(0); on = access("/tmp/oah_glitrace.on", 0) == 0; }
        if (!on) return;
    } else if (delay) { if (!t0) t0 = time(0); if (time(0) - t0 < delay) return; }
    if (strcmp(tl, "all")) {
        ln = strlen(nm); p = strstr(tl, nm);
        if (!p || !((p == tl || p[-1] == ',') && (p[ln] == 0 || p[ln] == ','))) return;
    }
    nl++;
    {   static U (*cur)(void); if (!cur) *(void **)&cur = oah_ogl_sym("CGLGetCurrentContext");
        fprintf(stderr, "[gli] %08x ", cur ? cur() : 0); }
    fprintf(stderr, "%s(%d, %d, %d, %d, %d) f1=%g f2=%g f3=%g f4=%g\n", nm, (int)R[3], (int)R[4], (int)R[5], (int)R[6], (int)R[7],
            ((double *)((unsigned char *)R + 0x1e8))[1], ((double *)((unsigned char *)R + 0x1e8))[2],
            ((double *)((unsigned char *)R + 0x1e8))[3], ((double *)((unsigned char *)R + 0x1e8))[4]);
}
/* bridge 13: a CGL dispatch-table entry (r11 = index, r3 = rend) */
static void br_gli_disp(unsigned int *R) {
    static int genidx[1024];
    static int (*getcur)(void), (*setcur)(U);
    unsigned int i = R[11], ne = sizeof g_gli_disp / sizeof g_gli_disp[0], k;
    unsigned char Rc[0x300];
    U *C = (U *)Rc, w = 0;
    const char *nm = i < ne ? g_gli_disp[i] : 0;
    if (!nm) { if (i >= ne || g_glxtrace) fprintf(stderr, "[gli] dispatch entry %u has no gl function\n", i); R[3] = 0; return; }
    if (!getcur) { getcur = (int (*)(void))oah_ogl_sym("CGLGetCurrentContext"); setcur = (int (*)(U))oah_ogl_sym("CGLSetCurrentContext"); }
    /* a call through another context's dispatch table (guest AGL's aglSurfaceTexture queries the
       source context this way) runs on that context but does not make it current: switch for the
       call and back afterwards. Leaving it current sent Build-a-lot 2's next draws (the opaque
       background quad of its sprite layer) to the source surface, and panels and arrows stayed. */
    U prevcur = 0;
    if (R[3] && getcur && setcur && (U)getcur() != R[3]) {
        prevcur = (U)getcur();
        if (!setcur(R[3])) oah_gl_ctx_made_current(R[3]); else prevcur = 0;
    }
    if (i < 1024 && !genidx[i]) {
        genidx[i] = -1;
        for (k = 0; k < OAH_NGEN; k++) if (!strcmp(g_gen[k].name, nm)) { genidx[i] = (int)k; break; }
    }
    /* drop rend: GPR args shift down one, and the guest parameter area is seen 4 bytes later */
    memcpy(Rc, R, sizeof Rc);
    for (k = 3; k < 10; k++) C[k] = R[k + 1];
    probe_read(R[1] + 56, &w); C[10] = OSSwapBigToHostInt32(w);
    C[1] = R[1] + 4;
    oah_gli_trace(nm, C);
    if (i < 1024 && genidx[i] >= 0) oah_gen_call((unsigned int)genidx[i], C);
    else oah_glx_gl(nm, C);
    R[3] = C[3]; R[4] = C[4];
    memcpy((unsigned char *)R + 0x1e8, Rc + 0x1e8, 16);   /* f0/f1 results */
    {   static int norestore = -1; if (norestore < 0) norestore = getenv("OAH_GLI_NORESTORE") ? 1 : 0;
        if (prevcur && !norestore && !setcur(prevcur)) oah_gl_ctx_made_current(prevcur); }
}
/* ---- CGL ---- */
static int oah_cgl_valued(U t) {
    switch (t) { case 7: case 8: case 11: case 12: case 13: case 14: case 55: case 56: case 70: case 84: case 99: return 1; }
    return 0;
}
/* guest attribute list -> native; strip: 1 drop renderer pinning, 2 also drop depth/stencil/aux minimums */
static int oah_cgl_attribs(U g, U *out, int max, int strip, char *desc, size_t dl) {
    int n = 0, o = 0; size_t dp = 0;
    if (desc && dl) desc[0] = 0;
    while (g && n < 120 && o < max - 2) {
        U t = OSSwapBigToHostInt32(((U *)g)[n++]), v = 0;
        int val = oah_cgl_valued(t);
        if (!t) break;
        if (val) v = OSSwapBigToHostInt32(((U *)g)[n++]);
        if (desc && dp < dl - 24) dp += snprintf(desc + dp, dl - dp, val ? "%u=%u " : "%u ", t, v);
        /* not on Mojave / meaningless here: FullScreen 54, OffScreen 53, DisplayMask 84, Window 80,
           MultiScreen 81, Compliant 83, Robust 75, MPSafe 78, PBuffer 90 */
        if (t == 54 || t == 53 || t == 84 || t == 80 || t == 81 || t == 83 || t == 75 || t == 78 || t == 90) continue;
        if (strip >= 1 && (t == 70 || t == 71 || t == 73 || t == 74)) continue;   /* RendererID SingleRenderer Accelerated ClosestPolicy */
        if (strip >= 2 && (t == 7 || t == 13 || t == 14 || t == 57)) continue;
        out[o++] = t;
        if (val) out[o++] = v;
    }
    /* Double-buffered formats get kCGLPFABackingStore (76): on 10.6 a window's back buffer kept
       its contents across CGLFlushDrawable, and games that redraw only what changed rely on it
       (Build-a-lot 2 showed stale panels and noise on Mojave, where it is undefined after a
       swap). OAH_NO_GLBACKING=1 leaves the format as asked. */
    if (!getenv("OAH_NO_GLBACKING") && o < max - 2) {
        int k2, dbl = 0, bs = 0;
        for (k2 = 0; k2 < o; k2++) { if (out[k2] == 5) dbl = 1; if (out[k2] == 76) bs = 1; }
        if (dbl && !bs) { out[o++] = 76; if (desc && dp < dl - 8) dp += snprintf(desc + dp, dl - dp, "+76 "); }
    }
    out[o] = 0;
    return o;
}
/* ---- the guest's own notion of the current context ----
   CGLMacro-style guest code (libGLU's gluPerspective, ...) does not call CGLGetCurrentContext:
   it reads libGL's _gll_cc cache (a context whose +0xbf8 holds the stack pointer of the thread
   that last used it) and falls back to pthread_getspecific(30). The guest libGL is all bridges,
   so neither was ever set and gluPerspective read 0->0xbf8 (Keynote Play). Keep both in step
   with CGLSetCurrentContext, using the shadow object (its +0xbf8 lies just past disp[764]). */
static unsigned int oah_callppc_n(const char *tag, unsigned int fn, int n, unsigned int *args);
static void oah_cgl_guest_current(U g, U guest_r1) {
    static U gllcc, setspec;
    static int looked;
    U a[2];
    if (!looked) {
        looked = 1;
        gllcc = oah_guest_sym("libGL.dylib", "_gll_cc");
        setspec = oah_guest_sym("libSystem", "_pthread_setspecific");
        fprintf(stderr, "[cgl] guest _gll_cc at %08x, pthread_setspecific %08x\n", gllcc, setspec);
    }
    if (setspec) { a[0] = 30; a[1] = g; oah_callppc_n("pthread_setspecific", setspec, 2, a); }
    if (g) ((U *)g)[0xbf8 / 4] = OSSwapHostToBigInt32(guest_r1);
    if (gllcc && g) *(U *)gllcc = OSSwapHostToBigInt32(g);
}

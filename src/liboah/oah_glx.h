/* oah_glx.h - generic OpenGL / CGL / CGS-surface bridge for guest Cocoa (NSOpenGL, GLUT) apps.
   oah_gl.h replays the calls SimCity 4 makes (AGL + its GL subset, with special emulation);
   everything else in the PowerPC libGL is marked too (bridges.spec, generated by genglx.py)
   and lands here: arguments are fetched by the prototype's signature (oah_glx_tab.h), array
   arguments are byte-swapped with element counts inferred from the function's name or pname,
   and the call is replayed on Mojave's i386 OpenGL.  CGL objects (pixel formats, contexts) are
   Mojave's own, handed to the guest as opaque handles.  NSOpenGLContext puts its drawable on
   a CGS surface of the window: CGSAddSurface & co. go to the native WindowServer on the same
   connection and window ids, and CGLSetSurface attaches the native context to it.
   OAH_GLXTRACE=1 logs the first calls of each function. */
#include "oah_glx_tab.h"
static void *g_ogl_handle;
static void *oah_ogl_sym(const char *n) {
    void *f;
    if (!g_ogl_handle) g_ogl_handle = dlopen("/System/Library/Frameworks/OpenGL.framework/OpenGL", RTLD_LAZY | RTLD_GLOBAL);
    f = g_ogl_handle ? dlsym(g_ogl_handle, n) : 0;
    return f;
}
static int g_glxtrace = -1;
static const oah_glx_ent *oah_glx_find(const char *n) {
    int lo = 0, hi = (int)(sizeof g_glx_tab / sizeof g_glx_tab[0]) - 1;
    while (lo <= hi) {
        int m = (lo + hi) / 2, c = strcmp(n, g_glx_tab[m].name);
        if (!c) return &g_glx_tab[m];
        if (c < 0) hi = m - 1; else lo = m + 1;
    }
    return 0;
}
/* element count of a light/material/texture/fog... parameter vector */
static int oah_glx_pname_count(const char *fn, U pname) {
    switch (pname) {
    case 0x1200: case 0x1201: case 0x1202: case 0x1203: case 0x1600: case 0x1602:   /* AMBIENT DIFFUSE SPECULAR POSITION EMISSION AMB_AND_DIFF */
    case 0x2201: case 0x1004: case 0x0B66: case 0x0B53: case 0x2501: case 0x2502:   /* TEX_ENV_COLOR BORDER_COLOR FOG_COLOR LIGHT_MODEL_AMBIENT OBJECT/EYE_PLANE */
        return 4;
    case 0x1204: case 0x1603: return 3;                                              /* SPOT_DIRECTION COLOR_INDEXES */
    }
    if (strstr(fn, "glGet") == fn && !strstr(fn, "TexLevelParameter") && !strstr(fn, "Light") &&
        !strstr(fn, "Material") && !strstr(fn, "TexEnv") && !strstr(fn, "TexParameter") && !strstr(fn, "TexGen"))
        return oah_gl_getcount(pname);
    return 1;
}
/* how many elements does pointer argument #ai (named an) of function fn point to? 0 = unknown */
static int oah_glx_count(const char *fn, const char *sig, const char *argn, int ai, U *val) {
    char names[16][32]; int nn = 0, i, d;
    const char *p = argn, *q;
    int L = (int)strlen(fn);
    while (*p && nn < 16) {
        q = strchr(p, ',');
        int l = q ? (int)(q - p) : (int)strlen(p);
        if (l > 31) l = 31;
        memcpy(names[nn], p, l); names[nn][l] = 0; nn++;
        if (!q) break;
        p = q + 1;
    }
    if (strstr(fn, "glUniformMatrix") == fn) {                    /* (location, count, transpose, value) */
        d = fn[15] - '0';
        if (d >= 2 && d <= 4 && fn[16] == 'f') return (int)val[1] * d * d;
        return 0;
    }
    if (strstr(fn, "glUniform") == fn && fn[9] >= '1' && fn[9] <= '4' && fn[L - 1] == 'v')
        return (int)val[1] * (fn[9] - '0');
    if (strstr(fn, "Matrix") && (strstr(fn, "glLoad") == fn || strstr(fn, "glMult") == fn)) return 16;
    {   /* ...3fv, ...4ubv, ...2dvARB: the digit before the type suffix */
        char b[64]; int k = L;
        strncpy(b, fn, 63); b[63] = 0;
        while (k > 0 && b[k - 1] >= 'A' && b[k - 1] <= 'Z') k--;           /* vendor suffix */
        if (k > 0 && b[k - 1] == 'v') {
            k--;
            while (k > 0 && strchr("bsifdu", b[k - 1])) k--;
            if (k > 0 && b[k - 1] >= '1' && b[k - 1] <= '4') return b[k - 1] - '0';
        }
    }
    for (i = 0; i < nn && i < 16; i++)
        if (!strcmp(names[i], "pname")) return oah_glx_pname_count(fn, val[i]);
    if (nn >= 2 && !strcmp(names[0], "n") && ai >= 1) return (int)val[0];
    if (!strcmp(fn, "glCallLists")) return (int)val[0];
    return 0;
}
static void oah_glx_swap(void *dst, const void *src, int n, int esz) {
    int i;
    const unsigned char *s = (const unsigned char *)src; unsigned char *t = (unsigned char *)dst;
    for (i = 0; i < n; i++, s += esz, t += esz) {
        if (esz == 2) { unsigned short v; memcpy(&v, s, 2); v = OSSwapInt16(v); memcpy(t, &v, 2); }
        else if (esz == 4) { U v; memcpy(&v, s, 4); v = OSSwapInt32(v); memcpy(t, &v, 4); }
        else if (esz == 8) { unsigned long long v; memcpy(&v, s, 8); v = OSSwapInt64(v); memcpy(t, &v, 8); }
        else memcpy(t, s, esz);
    }
}

/* ---- arrays the generic path cannot pass through ----
   generic vertex attributes (glVertexAttribPointer[ARB]) are emulated like oah_gl.h's client
   arrays: recorded here, converted to native byte order for the index range of each draw;
   glDrawRangeElements converts its indices like glDrawElements; glShaderSource[ARB] gets
   native pointer and length arrays. */
#define OAH_NATTR 16
static struct { int size, type, norm, stride, en; U ptr; } g_attr[OAH_NATTR];
static unsigned g_attr_nat;                          /* natively enabled attribute arrays */
static unsigned char *g_attr_scr[OAH_NATTR]; static size_t g_attr_scn[OAH_NATTR];
/* Attribute array state (the guest's and what is enabled natively) belongs to the GL context.
   It was global: Pages' second Template Chooser got a fresh context, the bridge believed its
   attribute arrays were already enabled from the first chooser's context, never enabled them,
   and every draw came out empty (black grid). Swap the state in and out per context. */
#define OAH_NATTRCTX 32
static struct { U ctx; struct { int size, type, norm, stride, en; U ptr; } a[OAH_NATTR]; unsigned nat; } g_attr_ctx[OAH_NATTRCTX];
static U g_attr_cur;
static void oah_attr_sync(void) {
    int i, sv = -1, ld = -1, fr = -1;
    if (g_attr_cur == g_cur_ctx || getenv("OAH_NO_ATTRCTX")) return;
    for (i = 0; i < OAH_NATTRCTX; i++) {
        if (g_attr_ctx[i].ctx == g_attr_cur && g_attr_cur) sv = i;
        if (g_attr_ctx[i].ctx == g_cur_ctx) ld = i;
        if (!g_attr_ctx[i].ctx && fr < 0) fr = i;
    }
    if (g_attr_cur) {
        if (sv < 0) sv = fr >= 0 ? fr : 0;
        if (sv == fr) fr = -1;
        g_attr_ctx[sv].ctx = g_attr_cur;
        memcpy(g_attr_ctx[sv].a, g_attr, sizeof g_attr); g_attr_ctx[sv].nat = g_attr_nat;
        if (fr < 0) for (i = 0; i < OAH_NATTRCTX; i++) if (!g_attr_ctx[i].ctx) { fr = i; break; }
    }
    if (ld >= 0) { memcpy(g_attr, g_attr_ctx[ld].a, sizeof g_attr); g_attr_nat = g_attr_ctx[ld].nat; }
    else { memset(g_attr, 0, sizeof g_attr); g_attr_nat = 0; }   /* a new context: nothing enabled */
    g_attr_cur = g_cur_ctx;
}
static void oah_attr_forget(U ctx) {
    int i; for (i = 0; i < OAH_NATTRCTX; i++) if (g_attr_ctx[i].ctx == ctx) g_attr_ctx[i].ctx = 0;
    if (g_attr_cur == ctx) g_attr_cur = 0;
}
static void oah_glx_setup_attribs(int lo, int hi) {
    static void (*vap)(U, U, U, U, U, U), (*ena)(U), (*dis)(U);
    int k, n = hi - lo + 1;
    oah_attr_sync();
    if (!vap) { vap = (void (*)(U, U, U, U, U, U))oah_ogl_sym("glVertexAttribPointerARB");
                ena = (void (*)(U))oah_ogl_sym("glEnableVertexAttribArrayARB"); dis = (void (*)(U))oah_ogl_sym("glDisableVertexAttribArrayARB"); }
    if (!vap || n <= 0) return;
    for (k = 0; k < OAH_NATTR; k++) {
        if (g_attr[k].en && g_attr[k].ptr) {
            int ts = oah_tsz(g_attr[k].type), esz = g_attr[k].size * ts, st = g_attr[k].stride ? g_attr[k].stride : esz;
            size_t need = (size_t)n * esz;
            const unsigned char *s = (const unsigned char *)g_attr[k].ptr + (size_t)lo * st;
            unsigned char *d;
            int i;
            if (g_attr_scn[k] < need) { free(g_attr_scr[k]); g_attr_scn[k] = need + need / 2 + 256; g_attr_scr[k] = (unsigned char *)malloc(g_attr_scn[k]); }
            d = g_attr_scr[k];
            for (i = 0; i < n; i++, s += st, d += esz) oah_glx_swap(d, s, g_attr[k].size, ts);
            vap((U)k, (U)g_attr[k].size, (U)g_attr[k].type, (U)g_attr[k].norm, 0, (U)(g_attr_scr[k] - (size_t)lo * esz));
            if (!(g_attr_nat & (1u << k))) { ena((U)k); g_attr_nat |= 1u << k; }
        } else if (g_attr_nat & (1u << k)) { dis((U)k); g_attr_nat &= ~(1u << k); }
    }
}
static int oah_glx_special(const char *n, U *R) {
    if (n[2] == 'V' || n[2] == 'E' || n[2] == 'D') oah_attr_sync();
    if (!strncmp(n, "glVertexAttribPointer", 21)) {          /* (index, size, type, normalized, stride, ptr) */
        U i = R[3];
        if (i < OAH_NATTR) { g_attr[i].size = (int)R[4]; g_attr[i].type = (int)R[5]; g_attr[i].norm = (int)(R[6] & 0xff);
                             g_attr[i].stride = (int)R[7]; g_attr[i].ptr = R[8]; }
        g_gl_attr_hook = oah_glx_setup_attribs;
        return 1;
    }
    if (!strncmp(n, "glEnableVertexAttribArray", 25) || !strncmp(n, "glDisableVertexAttribArray", 26)) {
        if (R[3] < OAH_NATTR) g_attr[R[3]].en = n[2] == 'E';
        g_gl_attr_hook = oah_glx_setup_attribs;
        return 1;
    }
    if (!strncmp(n, "glDrawRangeElements", 19)) {             /* (mode, start, end, count, type, indices) */
        static void (*f)(U, U, U, U, U, U);
        int cnt = (int)R[6], isz = R[7] == 0x1401 ? 1 : R[7] == 0x1403 ? 2 : 4, i, lo = 0x7fffffff, hi = -1;
        unsigned char *ib;
        U ebuf = 0;
        if (!f) f = (void (*)(U, U, U, U, U, U))oah_ogl_sym("glDrawRangeElements");
        if (cnt <= 0 || !f) return 1;
        {   void (*gi)(U, U *) = (void (*)(U, U *))oah_ogl_sym("glGetIntegerv");
            if (gi) gi(0x8895, &ebuf); }                       /* ELEMENT_ARRAY_BUFFER_BINDING */
        if (ebuf || !R[8]) { oah_gl_setup_arrays((int)R[4], (int)R[5]); f(R[3], R[4], R[5], R[6], R[7], R[8]); return 1; }
        ib = oah_scratch(OAH_SCR_IDX, (size_t)cnt * isz);
        for (i = 0; i < cnt; i++) {
            U v;
            if (isz == 1) v = ((unsigned char *)R[8])[i];
            else if (isz == 2) { unsigned short s; memcpy(&s, (unsigned char *)R[8] + 2 * i, 2); v = OSSwapInt16(s); ((unsigned short *)ib)[i] = (unsigned short)v; }
            else { memcpy(&v, (unsigned char *)R[8] + 4 * i, 4); v = OSSwapInt32(v); ((U *)ib)[i] = v; }
            if (isz == 1) ib[i] = (unsigned char)v;
            if ((int)v < lo) lo = (int)v;
            if ((int)v > hi) hi = (int)v;
        }
        oah_gl_setup_arrays(lo, hi);
        f(R[3], R[4], R[5], R[6], R[7], (U)ib);
        return 1;
    }
    if (!strncmp(n, "glShaderSource", 14)) {                 /* (shader, count, const char **strings, const GLint *lengths) */
        static void (*f)(U, U, const char **, const int *);
        int c = (int)R[4], i;
        const char **sp; int *lp = 0;
        if (!f) f = (void (*)(U, U, const char **, const int *))oah_ogl_sym("glShaderSourceARB");
        if (c <= 0 || c > 4096 || !f) return 1;
        sp = (const char **)malloc(sizeof *sp * c);
        if (R[6]) lp = (int *)malloc(sizeof *lp * c);
        for (i = 0; i < c; i++) {
            sp[i] = (const char *)OSSwapBigToHostInt32(((U *)R[5])[i]);
            if (lp) lp[i] = (int)OSSwapBigToHostInt32(((U *)R[6])[i]);
        }
        f(R[3], (U)c, sp, lp);
        free(sp); free(lp);
        return 1;
    }
    return 0;
}
typedef U (*oah_glx16_t)(U, U, U, U, U, U, U, U, U, U, U, U, U, U, U, U);
static int oah_glx_gl(const char *n, U *R) {
    const oah_glx_ent *e = oah_glx_find(n);
    static void *fns[2048]; static char done[2048];
    double *F = (double *)((unsigned char *)R + 0x1e8);
    U a[16], val[16], ret;
    int na = 0, gr = 0, fr = 1, ai = 0, idx, k;
    struct { U g; void *tmp; int cnt, esz, out; } fx[6]; int nfx = 0;
    const char *p;
    if (!e) return 0;
    if (oah_ctxtrace()) fprintf(stderr, "[glctx] %08x %s(%x, %x, %x, %x) f1=%g f2=%g\n", g_cur_ctx, n, R[3], R[4], R[5], R[6], F[1], F[2]);
    if (oah_glx_special(n, R)) return 1;
    idx = (int)(e - g_glx_tab);
    if (idx < 2048 && !done[idx]) { done[idx] = 1; fns[idx] = oah_ogl_sym(n); }
    if (g_glxtrace < 0) g_glxtrace = getenv("OAH_GLXTRACE") != 0;
    if (idx >= 2048 || !fns[idx]) {
        fprintf(stderr, "[glx] %s: no native function\n", n);
        R[3] = 0; return 1;
    }
    /* fetch: GPR words 0..7 in r3..r10, then the parameter area on the guest stack */
    for (p = e->sig + 2; *p && na < 16; ) {
        char c = *p;
        if (c == 'f' || c == 'd') {
            double v = F[fr++];
            if (c == 'f') { float f = (float)v; memcpy(&a[na++], &f, 4); gr += 1; }
            else { memcpy(&a[na], &v, 8); na += 2; gr += 2; }
            val[ai < 16 ? ai : 15] = 0;
            ai++; p++;
        } else if (c == 'l') {
            U hi = oah_garg(R, gr), lo = oah_garg(R, gr + 1);
            gr += 2; a[na++] = lo; a[na++] = hi;
            val[ai < 16 ? ai : 15] = lo; ai++; p++;
        } else if (c == 'i') {
            U v = oah_garg(R, gr++);
            a[na++] = v; val[ai < 16 ? ai : 15] = v; ai++; p++;
        } else {   /* P<n> / Q<n> */
            U v = oah_garg(R, gr++);
            int esz = p[1] - '0', out = c == 'Q';
            val[ai < 16 ? ai : 15] = v;
            a[na] = v;
            if (v && esz > 1 && nfx < 6) {
                int cnt = oah_glx_count(n, e->sig, e->argn, ai, val);
                if (cnt > 0 && cnt < (1 << 20)) {
                    void *t = malloc((size_t)cnt * esz);
                    if (t) {
                        oah_glx_swap(t, (void *)v, cnt, esz);
                        fx[nfx].g = v; fx[nfx].tmp = t; fx[nfx].cnt = cnt; fx[nfx].esz = esz; fx[nfx].out = out; nfx++;
                        a[na] = (U)t;
                    }
                } else if (g_glxtrace) fprintf(stderr, "[glx] %s: pointer arg %d passed raw\n", n, ai);
            }
            na++; ai++; p += 2;
        }
        if (*p == ',') p++;
    }
    for (k = na; k < 16; k++) a[k] = 0;
    if (!strcmp(n, "glCallLists") && nfx == 0 && a[2]) {   /* (n, type, lists): element size from type */
        int esz = val[1] == 0x1402 || val[1] == 0x1403 ? 2 : (val[1] == 0x1404 || val[1] == 0x1405 || val[1] == 0x1406) ? 4 : 1;
        if (esz > 1) {
            void *t = malloc((size_t)val[0] * esz);
            if (t) { oah_glx_swap(t, (void *)val[2], (int)val[0], esz); a[2] = (U)t;
                     fx[0].g = 0; fx[0].tmp = t; fx[0].out = 0; nfx = 1; }
        }
    }
    ret = ((oah_glx16_t)fns[idx])(a[0], a[1], a[2], a[3], a[4], a[5], a[6], a[7], a[8], a[9], a[10], a[11], a[12], a[13], a[14], a[15]);
    for (k = 0; k < nfx; k++) {
        if (fx[k].out && fx[k].g) oah_glx_swap((void *)fx[k].g, fx[k].tmp, fx[k].cnt, fx[k].esz);
        free(fx[k].tmp);
    }
    if (e->sig[0] == 'b') ret &= 0xff;
    if (e->sig[0] != 'v') R[3] = ret;
    if (g_glxtrace) {
        static unsigned short seen[2048];
        if (idx < 2048 && seen[idx] < 3) { seen[idx]++; fprintf(stderr, "[glx] %s(%08x %08x %08x %08x) -> %08x\n", n, a[0], a[1], a[2], a[3], ret); }
    }
    return 1;
}

/* ---- CGL contexts as the guest sees them ----
   struct _CGLContextObject { GLIContext rend; GLIFunctionDispatch disp; priv; stak; } is public, and
   CGLMacro users (QuartzCore, ...) call cgl_ctx->disp.fn(cgl_ctx->rend, args) directly.  The guest
   therefore gets a shadow object: rend = the native context, disp = one PowerPC thunk per entry
   ("li r11,index; twi 31,r0,13; blr") that lands in br_gli_disp, which makes rend current, drops it
   from the argument list and runs the matching gl* bridge. */
#define OAH_NSHADOW 64
static struct { U guest, native; } g_shadow[OAH_NSHADOW];
static pthread_mutex_t g_shadow_mu = PTHREAD_MUTEX_INITIALIZER;
static U g_gli_thunks;     /* guest code: 3 words per dispatch entry */
static U oah_cgl_native(U g) {
    int i;
    if (!g) return 0;
    for (i = 0; i < OAH_NSHADOW; i++) if (g_shadow[i].guest == g) return g_shadow[i].native;
    return g;                                   /* not a shadow: already native */
}
/* Where the thunks live.  The translator only keeps running guest code that lies inside a
   loaded image (code in an anonymous page works until its code-region table is recycled, then
   Rosetta logs a fatal error and exits(1): Keynote died that way at its first texture upload).
   Every gl* function in the guest libGL is a bridge ("twi 31,r0,id; blr") whose old body is
   dead, so the thunks go there: entry i in the body of its own gl function when it has one,
   the rest in the spare bodies of others. */
static U g_gli_thunk_at[1024];
static unsigned int oah_guest_sym(const char *lib, const char *sym);
static const char *oah_guest_image_name(unsigned int addr, unsigned int *base_out);
static int oah_guest_syms_each(unsigned int p, void (*fn)(const char *, unsigned int, void *), void *ctx);
#define OAH_GLSYM_MAX 4096
struct oah_glsyms { int n; U a[OAH_GLSYM_MAX]; const char *nm[OAH_GLSYM_MAX]; U lo[OAH_GLSYM_MAX], hi[OAH_GLSYM_MAX]; };
static void oah_glsym_cb(const char *nm, unsigned int a, void *c) {
    struct oah_glsyms *s = (struct oah_glsyms *)c;
    if (s->n < OAH_GLSYM_MAX) { s->a[s->n] = a; s->nm[s->n] = nm; s->n++; }
}
static void oah_gli_build_thunks(int ne) {
    static struct oah_glsyms s;
    U base = 0, fl = oah_guest_sym("libGL.dylib", "_glFlush"), wlo = ~0u, whi = 0;
    int i, j, k, placed_own = 0, placed_pool = 0;
    if (fl) oah_guest_image_name(fl, &base);
    if (base) { s.n = 0; oah_guest_syms_each(base, oah_glsym_cb, &s); }
    if (!base || s.n < 100) { fprintf(stderr, "[cgl] no guest libGL symbols (%d); dispatch thunks unavailable\n", s.n); return; }
    /* sort by address (insertion sort is fine for ~1000) */
    for (i = 1; i < s.n; i++) {
        U a = s.a[i]; const char *nm = s.nm[i];
        for (j = i - 1; j >= 0 && s.a[j] > a; j--) { s.a[j + 1] = s.a[j]; s.nm[j + 1] = s.nm[j]; }
        s.a[j + 1] = a; s.nm[j + 1] = nm;
    }
    for (k = 0; k < s.n; k++) {
        U pw[8], w0, w1, nx = 0;
        s.lo[k] = s.hi[k] = 0;
        if (!oah_peek2(s.a[k], pw)) continue;
        w0 = OSSwapBigToHostInt32(pw[0]); w1 = OSSwapBigToHostInt32(pw[1]);
        for (j = k + 1; j < s.n && s.a[j] == s.a[k]; j++) ;
        if (j < s.n) nx = s.a[j];
        s.lo[k] = s.hi[k] = 0;
        if (k > 0 && s.a[k - 1] == s.a[k]) continue;   /* alias: the first name owns the body */
        if (nx && (w0 & 0xffff0000u) == 0x0fe00000u && w1 == 0x4e800020u && nx - s.a[k] >= 20 && nx - s.a[k] < 0x10000) {
            s.lo[k] = s.a[k] + 8; s.hi[k] = nx;
        }
    }
    memset(g_gli_thunk_at, 0, sizeof g_gli_thunk_at);
    for (i = 0; i < ne && i < 1024; i++) {         /* pass 1: own function body */
        const char *nm = g_gli_disp[i];
        if (nm) for (k = 0; k < s.n; k++)
            if (s.nm[k][0] == '_' && !strcmp(s.nm[k] + 1, nm)) {
                if (s.hi[k] - s.lo[k] >= 12) { g_gli_thunk_at[i] = s.lo[k]; s.lo[k] += 12; placed_own++; }
                break;
            }
    }
    k = 0;
    for (i = 0; i < ne && i < 1024; i++) {         /* pass 2: spare room anywhere */
        if (g_gli_thunk_at[i]) continue;
        while (k < s.n && s.hi[k] - s.lo[k] < 12) k++;
        if (k >= s.n) break;
        g_gli_thunk_at[i] = s.lo[k]; s.lo[k] += 12; placed_pool++;
    }
    for (i = 0; i < ne && i < 1024; i++) {
        U at = g_gli_thunk_at[i];
        if (at) { if (at < wlo) wlo = at; if (at + 12 > whi) whi = at + 12; }
    }
    if (!whi) return;
    wlo &= ~0xfffu; whi = (whi + 0xfff) & ~0xfffu;
    if (vm_protect(mach_task_self(), wlo, whi - wlo, 0, VM_PROT_READ | VM_PROT_WRITE | VM_PROT_COPY) != KERN_SUCCESS) {
        fprintf(stderr, "[cgl] cannot write the guest libGL text; dispatch thunks unavailable\n");
        memset(g_gli_thunk_at, 0, sizeof g_gli_thunk_at);
        return;
    }
    for (i = 0; i < ne && i < 1024; i++) if (g_gli_thunk_at[i]) {
        U *t = (U *)g_gli_thunk_at[i];
        t[0] = OSSwapHostToBigInt32(0x39600000u | (U)i);   /* li r11,i */
        t[1] = OSSwapHostToBigInt32(0x0fe0000du);       /* twi 31,r0,13 */
        t[2] = OSSwapHostToBigInt32(0x4e800020u);       /* blr */
    }
    vm_protect(mach_task_self(), wlo, whi - wlo, 0, VM_PROT_READ | VM_PROT_EXECUTE);
    g_gli_thunks = wlo;
    fprintf(stderr, "[cgl] %d dispatch thunks in guest libGL (%d in their own function, %d in spare bodies, %d without room)\n",
            placed_own + placed_pool, placed_own, placed_pool, ne - placed_own - placed_pool);
}
static U oah_cgl_guest(U n) {
    int i, ne = (int)(sizeof g_gli_disp / sizeof g_gli_disp[0]);
    U g, *o;
    if (!n) return 0;
    pthread_mutex_lock(&g_shadow_mu);
    for (i = 0; i < OAH_NSHADOW; i++) if (g_shadow[i].native == n) { g = g_shadow[i].guest; pthread_mutex_unlock(&g_shadow_mu); return g; }
    { static int tried; if (!g_gli_thunks && !tried) { tried = 1; oah_gli_build_thunks(ne); } }
    o = (U *)calloc(1, 4 * (size_t)ne + 16 + 64);
    if (!o || !g_gli_thunks) { pthread_mutex_unlock(&g_shadow_mu); return n; }
    o[0] = OSSwapHostToBigInt32(n);
    for (i = 0; i < ne; i++) o[1 + i] = OSSwapHostToBigInt32(g_gli_thunk_at[i]);
    /* +0xbf4 (right after the 764 dispatch entries): CGL's private object. Guest AGL reads it
       from contexts it is handed (aglSurfaceTexture: byte +0x41; aglGetCurrentContext can return
       the CGL context itself), and a NULL there crashed Build-a-lot 2. A zeroed block reads as
       "no special state". */
    if (ne == 764) { void *priv = calloc(1, 0x400); if (priv) o[1 + ne] = OSSwapHostToBigInt32((U)priv); }
    for (i = 0; i < OAH_NSHADOW && g_shadow[i].guest; i++) ;
    if (i < OAH_NSHADOW) { g_shadow[i].guest = (U)o; g_shadow[i].native = n; }
    pthread_mutex_unlock(&g_shadow_mu);
    fprintf(stderr, "[cgl] shadow context %08x for native %08x (%d dispatch entries)\n", (U)o, n, ne);
    return (U)o;
}
static void oah_cgl_forget(U g) {
    int i;
    pthread_mutex_lock(&g_shadow_mu);
    for (i = 0; i < OAH_NSHADOW; i++) if (g_shadow[i].guest == g || g_shadow[i].native == g) g_shadow[i].guest = g_shadow[i].native = 0;
    pthread_mutex_unlock(&g_shadow_mu);
}

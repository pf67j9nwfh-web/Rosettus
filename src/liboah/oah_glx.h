static void *oah_ogl_sym(const char *n);
/* One flipped copy of the current context's front/back buffer into surface texture k: draw
   framebuffer = an FBO with the texture attached, read framebuffer = the window (0). The FBO is
   kept per entry and context. Returns 0 (caller falls back) if the blit or FBO is unavailable. */
static struct { U ctx, fbo; } g_stex_fbo[16];
static int oah_stex_blit(int k, int frontbuf, int oldrb) {
    static void (*gen)(int, U *), (*bindfb)(U, U), (*fbtex)(U, U, U, U, int), (*blit)(int, int, int, int, int, int, int, int, U, U);
    static U (*check)(U);
    static U (*cur)(void);
    static int looked, bad;
    void (*geti)(U, int *) = (void (*)(U, int *))oah_ogl_sym("glGetIntegerv");
    void (*rb)(U) = (void (*)(U))oah_ogl_sym("glReadBuffer");
    int oldread = 0, olddraw = 0, w = g_stex[k].w, h = g_stex[k].h;
    U ctx, st;
    if (!looked) {
        looked = 1;
        *(void **)&gen = oah_ogl_sym("glGenFramebuffersEXT");
        *(void **)&bindfb = oah_ogl_sym("glBindFramebufferEXT");
        *(void **)&fbtex = oah_ogl_sym("glFramebufferTexture2DEXT");
        *(void **)&blit = oah_ogl_sym("glBlitFramebufferEXT");
        *(void **)&check = oah_ogl_sym("glCheckFramebufferStatusEXT");
        *(void **)&cur = oah_ogl_sym("CGLGetCurrentContext");
    }
    if (bad || !gen || !bindfb || !fbtex || !blit || !check || !cur || !geti || !rb) return 0;
    ctx = cur();
    if (g_stex_fbo[k].ctx != ctx || !g_stex_fbo[k].fbo) { g_stex_fbo[k].fbo = 0; gen(1, &g_stex_fbo[k].fbo); g_stex_fbo[k].ctx = ctx; }
    if (!g_stex_fbo[k].fbo) return 0;
    geti(0x8CAA /* READ_FRAMEBUFFER_BINDING */, &oldread); geti(0x8CA6 /* DRAW_FRAMEBUFFER_BINDING */, &olddraw);
    bindfb(0x8CA9 /* DRAW_FRAMEBUFFER */, g_stex_fbo[k].fbo);
    fbtex(0x8CA9, 0x8CE0 /* COLOR_ATTACHMENT0 */, g_stex[k].target, g_stex[k].tex, 0);
    st = check(0x8CA9);
    if (st != 0x8CD5 /* COMPLETE */) {
        bindfb(0x8CA9, (U)olddraw);
        fprintf(stderr, "[cgl] surface texture: FBO incomplete (%#x), copying row by row\n", st);
        bad = 1; return 0;
    }
    bindfb(0x8CA8 /* READ_FRAMEBUFFER */, 0);
    rb(frontbuf ? 0x0404 : 0x0405);
    blit(0, 0, w, h, 0, h, w, 0, 0x4000 /* COLOR_BUFFER_BIT */, 0x2600 /* NEAREST */);
    rb((U)oldrb);
    bindfb(0x8CA8, (U)oldread); bindfb(0x8CA9, (U)olddraw);
    return 1;
}
static void oah_stex_copy(int k, int frontbuf) {
    void (*bind)(U, U) = (void (*)(U, U))oah_ogl_sym("glBindTexture");
    void (*geti)(U, int *) = (void (*)(U, int *))oah_ogl_sym("glGetIntegerv");
    void (*rb)(U) = (void (*)(U))oah_ogl_sym("glReadBuffer");
    void (*cti)(U, int, U, int, int, int, int, int) = (void (*)(U, int, U, int, int, int, int, int))oah_ogl_sym("glCopyTexImage2D");
    void (*ctsi)(U, int, int, int, int, int, int, int) = (void (*)(U, int, int, int, int, int, int, int))oah_ogl_sym("glCopyTexSubImage2D");
    int oldtex = 0, oldrb = 0;
    U target = g_stex[k].target, bindq = target == 0x84F5 ? 0x84F6 : 0x8069;   /* TEXTURE_RECTANGLE / TEXTURE_2D bindings */
    if (!bind || !geti || !rb || !cti || !ctsi) return;
    geti(bindq, &oldtex); geti(0x0C02 /* READ_BUFFER */, &oldrb);
    rb(frontbuf ? 0x0404 : 0x0405);                 /* GL_FRONT / GL_BACK */
    bind(target, g_stex[k].tex);
    if (!g_stex[k].defined) { cti(target, 0, g_stex[k].ifmt ? g_stex[k].ifmt : 0x1908, 0, 0, g_stex[k].w, g_stex[k].h, 0); g_stex[k].defined = 1; }
    /* 10.6 surface textures are top row first (the window's orientation); GL copies bottom-up.
       Flip in one framebuffer blit into an FBO the texture is attached to; the row-by-row
       glCopyTexSubImage2D this replaced cost one GPU copy per row each frame (Build-a-lot 2's
       intro took ~90 s). OAH_STEX_ROWCOPY=1 copies row by row, OAH_STEX_NOFLIP=1 as is. */
    {   static int noflip = -1, rowcopy = -1; int y, h = g_stex[k].h, done = 0;
        if (noflip < 0) noflip = getenv("OAH_STEX_NOFLIP") ? 1 : 0;
        if (rowcopy < 0) rowcopy = getenv("OAH_STEX_ROWCOPY") ? 1 : 0;
        if (!noflip && !rowcopy) done = oah_stex_blit(k, frontbuf, oldrb);
        if (done) ;
        else if (noflip) ctsi(target, 0, 0, 0, 0, 0, g_stex[k].w, h);
        else for (y = 0; y < h; y++) ctsi(target, 0, 0, h - 1 - y, 0, y, g_stex[k].w, 1);
    }
    bind(target, (U)oldtex); rb((U)oldrb);
}
static void oah_stex_set(U dctx, U sid, U target, U ifmt, int w, int h) {
    U (*cur)(void) = (U (*)(void))oah_ogl_sym("CGLGetCurrentContext");
    int (*setcur)(U) = (int (*)(U))oah_ogl_sym("CGLSetCurrentContext");
    void (*geti)(U, int *) = (void (*)(U, int *))oah_ogl_sym("glGetIntegerv");
    U was = cur ? cur() : 0, sctx = 0;
    int k, tex = 0, i;
    if (!geti || !setcur) return;
    if (was != dctx) setcur(dctx);
    geti(target == 0x84F5 ? 0x84F6 : 0x8069, &tex);
    for (k = 0; k < 16 && g_stex[k].sid && !(g_stex[k].sid == sid && g_stex[k].tex == (U)tex); k++) ;
    if (k == 16) k = 15;
    g_stex[k].sid = sid; g_stex[k].tex = (U)tex; g_stex[k].target = target; g_stex[k].ifmt = ifmt;
    if (g_stex[k].w != w || g_stex[k].h != h) g_stex[k].defined = g_stex[k].fresh = 0;
    g_stex[k].w = w; g_stex[k].h = h;
    for (i = 0; i < 64; i++) if (g_glsurf[i].sid == sid && g_glsurf[i].ctx) { sctx = g_glsurf[i].ctx; break; }
    /* what the surface shows now -- unless a flush already copied its latest frame: the swap of a
       hidden source is skipped, so its front buffer is stale (Build-a-lot 2 re-binds the surface
       texture every frame; copying the front buffer each time left old panels on screen) */
    if (sctx && !(g_stex[k].defined && g_stex[k].fresh)) { setcur(sctx); oah_stex_copy(k, 1); }
    if (sctx && cur && cur() == sctx && sctx != was && !getenv("OAH_NO_STEX_FLUSH")) {   /* see oah_stex_on_flush */
        void (*glf)(void) = (void (*)(void))oah_ogl_sym("glFlush"); if (glf) glf();
    }
    setcur(was);
    if (getenv("OAH_STEXTRACE")) fprintf(stderr, "[cgl] surface texture: surface %u -> texture %d (target %x, %dx%d, ifmt %x), source ctx %08x\n",
                                         sid, tex, target, w, h, ifmt, sctx);
}
/* before the native CGLFlushDrawable of ctx (current): refresh textures bound to its surface */
static int oah_stex_on_flush(U ctx) {
    U (*cur)(void);
    int (*setcur)(U);
    U was, sid = 0;
    int i, k;
    if (!g_stex[0].sid) return 0;
    for (i = 0; i < 64; i++) if (g_glsurf[i].ctx == ctx) { sid = g_glsurf[i].sid; break; }
    if (!sid) return 0;
    for (k = 0; k < 16 && g_stex[k].sid; k++) if (g_stex[k].sid == sid) break;
    if (k == 16 || !g_stex[k].sid) return 0;
    cur = (U (*)(void))oah_ogl_sym("CGLGetCurrentContext"); setcur = (int (*)(U))oah_ogl_sym("CGLSetCurrentContext");
    if (!cur || !setcur) return 0;
    was = cur();
    if (was != ctx) setcur(ctx);
    for (; k < 16 && g_stex[k].sid; k++) if (g_stex[k].sid == sid) { oah_stex_copy(k, 0); g_stex[k].fresh = 1; }
    /* the texture is drawn from other contexts of the share group next: submit the copy in this
       one first (Apple: flush in the context that changed a shared texture). Without it Build-a-lot
       2's visible context drew its loading screen from a texture whose copy was still queued in a
       hidden context, and the screen stayed black around the progress bar. OAH_NO_STEX_FLUSH=1: off */
    if (!getenv("OAH_NO_STEX_FLUSH")) { static void (*glf)(void); if (!glf) *(void **)&glf = oah_ogl_sym("glFlush"); if (glf) glf(); }
    {   static int tr = -1; static unsigned long n[16];
        if (tr < 0) tr = getenv("OAH_STEXTRACE") ? 1 : 0;
        for (k = 0; tr && k < 16 && g_stex[k].sid; k++) if (g_stex[k].sid == sid && (++n[k] <= 3 || n[k] % 200 == 0))
            fprintf(stderr, "[cgl] surface texture: flush of ctx %08x refreshed texture %u (surface %u) #%lu\n", ctx, g_stex[k].tex, sid, n[k]); }
    {   /* OAH_STEX_DUMP=1: every 100th refresh, write each texture to /tmp/stex_<tex>.ppm (debug) */
        static int dump = -1, every = 100; static unsigned long dn;
        if (dump < 0) { dump = getenv("OAH_STEX_DUMP") ? atoi(getenv("OAH_STEX_DUMP")) : 0; if (getenv("OAH_STEX_DUMPN")) every = atoi(getenv("OAH_STEX_DUMPN")); if (every < 1) every = 1; }
        if (dump && ++dn % every == 0 && !(getenv("OAH_STEX_DUMPMAX") && dn > (unsigned long)atol(getenv("OAH_STEX_DUMPMAX")))) {
            void (*gti)(U, int, U, U, void *) = (void (*)(U, int, U, U, void *))oah_ogl_sym("glGetTexImage");
            void (*bind)(U, U) = (void (*)(U, U))oah_ogl_sym("glBindTexture");
            void (*geti)(U, int *) = (void (*)(U, int *))oah_ogl_sym("glGetIntegerv");
            for (k = 0; gti && bind && geti && k < 16 && g_stex[k].sid; k++) {
                int w = g_stex[k].w, h = g_stex[k].h, old = 0, y, x; unsigned char *b = malloc((size_t)w * h * 4); char fn[64]; FILE *f;
                U q = g_stex[k].target == 0x84F5 ? 0x84F6 : 0x8069;
                if (!b) continue;
                geti(q, &old); bind(g_stex[k].target, g_stex[k].tex);
                gti(g_stex[k].target, 0, 0x1908, 0x1401, b);
                bind(g_stex[k].target, (U)old);
                if (dump == 2) snprintf(fn, sizeof fn, "/tmp/stexd/%05lu_%u.ppm", dn, g_stex[k].tex);   /* OAH_STEX_DUMP=2: keep each dump */
                else snprintf(fn, sizeof fn, "/tmp/stex_%u.ppm", g_stex[k].tex);
                if ((f = fopen(fn, "wb"))) {
                    fprintf(f, "P6\n%d %d\n255\n", w, h);
                    for (y = 0; y < h; y++) for (x = 0; x < w; x++) fwrite(b + ((size_t)y * w + x) * 4, 1, 3, f);
                    fclose(f);
                }
                free(b);
            }
        } }
    if (was != ctx) setcur(was);
    return 1;
}
